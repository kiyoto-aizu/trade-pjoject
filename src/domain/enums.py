"""
================================================================================
列挙型定義モジュール
取引システムで使用される定数値を列挙型として定義しています。
================================================================================
"""
from enum import Enum


# ================================================================================
# 注文タイプ
# ================================================================================

class OrderSide(str, Enum):
    """
    注文の売買方向を表す列挙型。
    
    Attributes:
        SELL: 売却注文
        BUY: 買付注文
    """
    SELL = "1"
    BUY = "2"


# ================================================================================
# ランキング種別
# ================================================================================

class RankingType(str, Enum):
    """
    ランキングデータの種別を表す列挙型。
    
    Attributes:
        PRICE_GAIN: 値上がり率ランキング
        TURNOVER: 出来高ランキング
    """
    PRICE_GAIN = "1"
    TURNOVER = "4"
